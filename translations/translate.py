ET.register_namespace('', '')
tree = ET.parse(TS_FILE)
root = tree.getroot()

count = 0
for msg in root.iter('message'):
    src = msg.find('source')
    trans = msg.find('translation')
    if src is not None and src.text is not None and trans is not None:
        if trans.get('type') == 'unfinished':
            txt = src.text
            if txt in translations:
                trans.text = translations[txt]
                del trans.attrib['type']
                count += 1

tree.write(TS_FILE, encoding='utf-8', xml_declaration=True)
print(f"Translated {count} strings")
